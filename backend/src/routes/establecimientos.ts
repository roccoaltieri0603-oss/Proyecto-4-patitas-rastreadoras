import { Router } from 'express';
import { requiereAutenticacion } from '../autenticacion/middleware.js';
import { requiereCampos, requierePermisos } from '../autorizacion/membresia.js';
import { crearEstablecimiento, listarEstablecimientos, obtenerEstablecimiento, actualizarEstablecimiento, eliminarEstablecimiento } from '../controllers/establecimiento.js';
import { obtenerPosicionGpsSimulado, guardarPosicionGpsSimulado } from '../controllers/gps-simulado.js';
import { actualizarGpsSimulado, listarGpsSimulados } from '../controllers/gps-simulados.js';
import { actualizarPuesto, actualizarResponsableGps, cambiarRol, crearPuesto, expulsarDePuesto, expulsarMiembro, generarInvitacion, modificarMiembro, obtenerEquipo, obtenerHistorialIngresosForzados, transferir, unirse } from '../controllers/equipo.js';
import { buscarLugar } from '../controllers/lugares.js';
import { descargarRegistroUsosExcel, obtenerRegistroUsos } from '../controllers/registro-usos.js';
import { asyncHandler } from '../http/async-handler.js';
import { lotesRouter } from './lotes.js';
import { historialRouter } from './historial.js';
import { climaRouter } from './clima.js';
import { sateliteRouter } from './satelite.js';
import { iaRouter } from './ia.js';
import { simulacionRouter } from './simulacion.js';
import { estimacionRouter } from './estimacion.js';
import { medicionesAlturaRouter } from './mediciones-altura.js';
import { notificacionesRouter } from './notificaciones.js';
import { entrarPuesto, requiereSesionOperativa, salirPuesto } from '../autenticacion/operativa.js';

export const establecimientosRouter = Router();
establecimientosRouter.use(requiereAutenticacion);
establecimientosRouter.get('/', asyncHandler(listarEstablecimientos));
establecimientosRouter.post('/', asyncHandler(crearEstablecimiento));
establecimientosRouter.post('/unirse', asyncHandler(unirse));
establecimientosRouter.post('/:establecimientoId/puestos/:puestoId/entrar', asyncHandler(entrarPuesto));
establecimientosRouter.post('/:establecimientoId/salir', asyncHandler(salirPuesto));
// Antes del :establecimientoId: no pertenece a ningún establecimiento (se usa para encontrar dónde crear el primero).
establecimientosRouter.get('/buscar-lugar', asyncHandler(buscarLugar));
establecimientosRouter.use('/:establecimientoId', requiereSesionOperativa);
establecimientosRouter.get('/:establecimientoId', asyncHandler(obtenerEstablecimiento));
establecimientosRouter.patch('/:establecimientoId', requiereCampos({ nombre: 'renombrar_establecimiento', polygon: 'editar_limite_establecimiento' }), asyncHandler(actualizarEstablecimiento));
establecimientosRouter.delete('/:establecimientoId', asyncHandler(eliminarEstablecimiento));
establecimientosRouter.get('/:establecimientoId/equipo', asyncHandler(obtenerEquipo));
establecimientosRouter.get('/:establecimientoId/equipo/ingresos-forzados', asyncHandler(obtenerHistorialIngresosForzados));
establecimientosRouter.post('/:establecimientoId/equipo/puestos', asyncHandler(crearPuesto));
establecimientosRouter.patch('/:establecimientoId/equipo/puestos/:puestoId', asyncHandler(actualizarPuesto));
establecimientosRouter.post('/:establecimientoId/equipo/puestos/:puestoId/integrantes/:userId/cambiar-rol', asyncHandler(cambiarRol));
establecimientosRouter.delete('/:establecimientoId/equipo/puestos/:puestoId/integrantes/:userId', asyncHandler(expulsarDePuesto));
establecimientosRouter.patch('/:establecimientoId/equipo/responsable-gps', asyncHandler(actualizarResponsableGps));
establecimientosRouter.patch('/:establecimientoId/equipo/:userId', asyncHandler(modificarMiembro));
establecimientosRouter.delete('/:establecimientoId/equipo/:userId', asyncHandler(expulsarMiembro));
establecimientosRouter.post('/:establecimientoId/invitaciones', asyncHandler(generarInvitacion));
establecimientosRouter.post('/:establecimientoId/transferir-principal', asyncHandler(transferir));
establecimientosRouter.get('/:establecimientoId/registro-usos.xlsx', asyncHandler(descargarRegistroUsosExcel));
establecimientosRouter.get('/:establecimientoId/registro-usos', asyncHandler(obtenerRegistroUsos));
establecimientosRouter.get('/:establecimientoId/gps-simulado', asyncHandler(obtenerPosicionGpsSimulado));
establecimientosRouter.put('/:establecimientoId/gps-simulado', asyncHandler(guardarPosicionGpsSimulado));
establecimientosRouter.get('/:establecimientoId/dispositivos-simulados', requierePermisos('ver_dispositivos_gps'), asyncHandler(listarGpsSimulados));
establecimientosRouter.patch('/:establecimientoId/dispositivos-simulados/:dispositivoId', requierePermisos('modificar_dispositivos_gps'), asyncHandler(actualizarGpsSimulado));
establecimientosRouter.use('/:establecimientoId/lotes', climaRouter, sateliteRouter, simulacionRouter, estimacionRouter, medicionesAlturaRouter, lotesRouter, historialRouter);
establecimientosRouter.use('/:establecimientoId/ia', iaRouter);
establecimientosRouter.use('/:establecimientoId/notificaciones', notificacionesRouter);
